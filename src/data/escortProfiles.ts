/**
 * Get escorts for a given city, sorted by serviceCount descending
 */
export function getEscortsByCity(city: string = '北京'): EscortProfile[] {
  const cleanCity = city.replace('市', '');
  if (ESCORT_PROFILES_BY_CITY[cleanCity]) {
    return [...ESCORT_PROFILES_BY_CITY[cleanCity]].sort((a, b) => b.serviceCount - a.serviceCount);
  }
  
  // If city not found, fallback to Beijing or generate tailored city entries
  const defaultList = ESCORT_PROFILES_BY_CITY['北京'] || [];
  return defaultList.map(item => ({
    ...item,
    city: cleanCity,
    serviceArea: `${cleanCity}市重点三甲医院及就近社区服务`
  })).sort((a, b) => b.serviceCount - a.serviceCount);
}

/**
 * Get all escorts as an array sorted by total order count descending
 */
export function getAllEscorts(): EscortProfile[] {
  return Object.values(ESCORT_PROFILES_BY_CITY).flat().sort((a, b) => b.serviceCount - a.serviceCount);
}

